import { useEffect, useState, type FormEvent } from "react";
import { Link, useNavigate } from "react-router-dom";

import { useAuth } from "../../../hooks/useAuth";
import { confirmTwoFactor, setupTwoFactor } from "../services/authService";
import type { TwoFactorSetupResponse } from "../types/twoFactor";
import { getApiError } from "../utils/getApiError";

export default function TwoFactorSetupPage() {
  const navigate = useNavigate();
  const { isAuthenticated, isLoading } = useAuth();

  const [setup, setSetup] = useState<TwoFactorSetupResponse | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState("");
  const [isLoadingSetup, setIsLoadingSetup] = useState(true);
  const [isSubmitting, setIsSubmitting] = useState(false);

  useEffect(() => {
    let isMounted = true;

    async function loadSetup() {
      try {
        const response = await setupTwoFactor();

        if (isMounted) {
          setSetup(response);
        }
      } catch (error: unknown) {
        if (isMounted) {
          setError(getApiError(error, "Unable to start two-factor setup."));
        }
      } finally {
        if (isMounted) {
          setIsLoadingSetup(false);
        }
      }
    }

    if (!isLoading && isAuthenticated) {
      void loadSetup();
    }

    return () => {
      isMounted = false;
    };
  }, [isLoading, isAuthenticated]);

  async function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();

    setError("");
    setIsSubmitting(true);

    try {
      await confirmTwoFactor({ code: code.trim() });

      navigate("/dashboard", { replace: true });
    } catch (error: unknown) {
      setError(
        getApiError(error, "Unable to confirm two-factor authentication."),
      );
    } finally {
      setIsSubmitting(false);
    }
  }

  if (isLoading) {
    return <p>Loading...</p>;
  }

  if (!isAuthenticated) {
    return null;
  }

  return (
    <main className="auth-page">
      <section className="auth-card">
        <h1>Set up two-factor authentication</h1>

        <p>
          Scan this QR code with your authenticator app. Then enter the
          six-digit code generated by the app.
        </p>

        {isLoadingSetup && <p>Generating your QR code...</p>}

        {setup && (
          <>
            <div>
              <img
                src={setup.qr_code}
                alt="Two-factor authentication QR code"
                width={250}
                height={250}
              />
            </div>

            <p>
              <strong>Can't scan the QR code?</strong>
            </p>

            <p>Enter this setup key manually:</p>

            <code>{setup.secret}</code>

            <form onSubmit={handleSubmit}>
              <label htmlFor="code">Authenticator code</label>

              <input
                id="code"
                type="text"
                inputMode="numeric"
                autoComplete="one-time-code"
                pattern="[0-9]{6}"
                maxLength={6}
                value={code}
                onChange={(event) => setCode(event.target.value)}
                placeholder="123456"
                required
              />

              {error && <p role="alert">{error}</p>}

              <button type="submit" disabled={isSubmitting}>
                {isSubmitting ? "Verifying..." : "Enable 2FA"}
              </button>
            </form>
          </>
        )}

        {!setup && error && <p role="alert">{error}</p>}

        <p>
          <Link to="/dashboard">Back to dashboard</Link>
        </p>
      </section>
    </main>
  );
}
